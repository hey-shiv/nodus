"""Render the home page's hero drawing and melodies from a real match into web/public/.

Run:  .venv/bin/python scripts/export_site_assets.py
The home page is static (fast, no database), but its drawing and sound are generated by the
same functions as the live demo, from the hero plan x Antibody 1 on the demo world.
"""
import json
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from nodus.db import get_graph  # noqa: E402
from nodus.lessons import active_lessons  # noqa: E402
from nodus.matcher import evaluate  # noqa: E402
from nodus.melody import melody_events, melody_wav  # noqa: E402
from nodus.severity import level  # noqa: E402
from nodus.svg import alignment_svg  # noqa: E402
from nodus.view import rows_for  # noqa: E402
from nodus.watch import run  # noqa: E402
from scripts.setup_demo import build  # noqa: E402

OUT = ROOT / "web" / "public" / "generated"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    g = get_graph(f"lab_export_{uuid.uuid4().hex[:8]}")
    try:
        build(g, "NODUS demo")
        les = next(l for l in active_lessons(g) if l["id"] == "antibody-1")
        r = evaluate(g, "plan-hero", les)
        lvl = level(r.k, r.n, r.missing, les["completion"])
        title = "Refresh tariff tables for every depot"
        (OUT / "hero-echo.svg").write_text(alignment_svg(les["name"], title, rows_for(g, "plan-hero", les, r),
                                                         r.k, r.n, lvl))
        states = [(c.holds, s["kind"] == "absent") for c, s in zip(r.conditions, les["conditions"])]
        comp = [c["id"] for c in les["conditions"]].index(les["completion"])
        (OUT / "melody-unresolved.wav").write_bytes(melody_wav(melody_events(les["id"], states, comp)))
        (OUT / "melody-resolved.wav").write_bytes(melody_wav(melody_events(les["id"], states, comp, True)))
        table = [{"plan": p, "lesson": res.lesson_id, "k": res.k, "n": res.n, "status": res.status}
                 for p, res in run(g)]
        (OUT / "world-results.json").write_text(json.dumps(table, indent=1))
        print(f"wrote {len(list(OUT.iterdir()))} files to {OUT.relative_to(ROOT)} (hero: {r.k}/{r.n} {lvl})")
    finally:
        g.delete()


if __name__ == "__main__":
    main()
